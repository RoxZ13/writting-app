import { expect, test } from '@playwright/test'

test('a new story opens a page you can type into, with typography', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Начать историю' }).click()
  await page.getByRole('button', { name: 'Писать главу' }).click()
  const editor = page.locator('.ProseMirror')
  await expect(editor).toBeVisible()
  await expect(page.locator('.scene-head-title')).toHaveValue('Глава 1')
  await expect(page.locator('.scene-head-chapter')).toHaveCount(0)
  await expect(page.locator('input[value="Первая сцена"]')).toHaveCount(0)
  await expect(page.locator('.scene-nav-tool')).toContainText('Главы')
  await expect(page.locator('.chapter-progress-trigger')).toHaveCount(0)
  await editor.click()
  await page.keyboard.type('- Привет... "Тест" -- проверка')
  await expect(page.locator('.chapter-progress-percent')).toHaveCount(0)
  await page.locator('.chapter-progress-trigger').click()
  const progress = page.getByRole('dialog', { name: /Прогресс главы/ })
  await expect(progress.locator('.chapter-progress-scenes')).toHaveCount(0)
  await expect(progress.getByRole('button', { name: 'Отметить главу готовой' })).toBeVisible()
  await progress.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await expect(editor.locator('p').first()).toHaveText('— Привет… «Тест» — проверка')
})

test('a new author can start from scenes and sees the empty idea pool', async ({ page, isMobile }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Начать историю' }).click()
  await expect(page.getByRole('button', { name: 'Писать главу' })).toBeVisible()
  await page.getByRole('button', { name: 'Разложить по сценам' }).click()
  await expect(page.locator('.board, .timeline')).toBeVisible()
  if (isMobile) await expect(page.getByText('Идеи сцен', { exact: true })).toBeVisible()
})
