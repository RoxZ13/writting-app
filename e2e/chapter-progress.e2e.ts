import { expect, test } from '@playwright/test'
import { aliveRows, openChapterProgress, openWorkspaceTab, setChapterMaximum, startStory, waitTextInDb } from './helpers'

test('a manuscript opts into one counter and can change goals without entering the text', async ({ page, isMobile }) => {
  const editor = await startStory(page)
  await editor.fill('Короткий текст.')
  await waitTextInDb(page, 'Короткий текст.')
  const counter = page.locator('.volume-trigger')
  await expect(counter).toHaveCount(0)
  await expect(page.locator('.editor-wrap .scene-head')).toHaveCount(0)
  await setChapterMaximum(page, 1500)
  await expect(counter).toHaveText(/15 из 1\s500 знаков/)
  await counter.click()
  const details = page.getByRole('dialog', { name: 'Объём текста' })
  await expect(details).toContainText('Авторские листы')
  await expect(details.locator('dd', { hasText: '≈ 1 мин' })).toBeVisible()
  await details.getByRole('button', { name: 'Отметить главу готовой' }).click()
  await expect(details.getByRole('button', { name: 'Вернуть главу в работу' })).toBeVisible()
  await expect.poll(async () => (await aliveRows<any>(page, 'scenes'))[0].status).toBe('done')
  await details.getByRole('button', { name: 'Закрыть', exact: true }).click()
  if (isMobile) {
    await page.getByRole('button', { name: 'Писать', exact: true }).click()
    await expect(counter).toBeHidden()
    await page.getByRole('button', { name: 'Готово', exact: true }).click()
    await expect(counter).toBeVisible()
  }

  await page.goto('/#/book')
  await page.locator('.book-section-list summary').filter({ hasText: /^План/ }).click()
  const setting = page.getByLabel('Показывать объём в редакторе')
  await expect(setting).toBeChecked()
  await setting.click()
  await expect.poll(async () => (await aliveRows<any>(page, 'projects'))[0].showVolume).toBe(false)
  await expect(setting).not.toBeChecked()
  await page.goto('/#/text')
  await expect(editor).toHaveText('Короткий текст.')
  await expect(counter).toHaveCount(0)
  const panel = await openChapterProgress(page)
  await expect(panel).toContainText(/15 из 1\s500 знаков/)
})

test('the board shows a thin chapter indicator with details on demand', async ({ page }) => {
  const editor = await startStory(page)
  await editor.fill('Глава началась.')
  await waitTextInDb(page, 'Глава началась.')
  await setChapterMaximum(page, 5000)
  await openWorkspaceTab(page, 'Доска')
  const progress = page.locator('.board-chapter-progress').first()
  await expect(progress.getByText('До верхнего ориентира', { exact: false })).toHaveCount(0)
  await progress.getByRole('button', { name: 'Объём главы' }).click()
  await expect(progress).toContainText(/из 5\s000 знаков/)
  await expect(progress).toContainText('До верхнего ориентира')
})

test('a publishing platform by itself does not enable the counter', async ({ page }) => {
  const editor = await startStory(page)
  await editor.fill('Черновик.')
  await waitTextInDb(page, 'Черновик.')
  await page.goto('/#/book')
  await page.locator('summary', { hasText: 'Публикация' }).click()
  const platform = page.getByRole('group', { name: 'Площадка публикации' }).getByRole('button', { name: 'Фикбук', exact: true })
  await platform.click()
  await expect(platform).toHaveAttribute('aria-pressed', 'true')
  await page.goto('/#/text')
  await expect(editor).toBeVisible()
  await expect(page.locator('.volume-trigger')).toHaveCount(0)
})
